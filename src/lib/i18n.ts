/** Textos con traducción alemana (las claves del diccionario). */
export type MessageKey = keyof typeof DE;

const DICTIONARIES: Record<Locale, Dictionary> = { es: {}, de: DE };

/** Traduce un texto español al idioma activo e interpola `{variables}`. */
export function translate(
  locale: Locale,
  text: string,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[locale][text] ?? text;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    vars[key] === undefined ? `{${key}}` : String(vars[key]),
  );
}
